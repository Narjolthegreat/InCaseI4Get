    static func text(_ key: Key, language: AppLanguage) -> String {
        table(for: language)[key] ?? english[key] ?? String(describing: key)
    }

    static func format(
        _ key: Key,
        language: AppLanguage,
        arguments: [CVarArg]
    ) -> String {
        String(
            format: text(key, language: language),
            locale: language.locale,
            arguments: arguments
        )
    }

    static func isComplete(for language: AppLanguage) -> Bool {
        table(for: language).count == Key.allCases.count
    }

