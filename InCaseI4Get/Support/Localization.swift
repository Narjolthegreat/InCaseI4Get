import Foundation

extension AppLanguage {
    static var current: AppLanguage {
        let code = UserDefaults.standard.string(forKey: "settings.languageCode")
        return AppLanguage(rawValue: code ?? "") ?? .english
    }

    var locale: Locale {
        Locale(identifier: rawValue)
    }

    func text(_ key: L10n.Key) -> String {
        L10n.text(key, language: self)
    }

    func format(_ key: L10n.Key, _ arguments: CVarArg...) -> String {
        L10n.format(key, language: self, arguments: arguments)
    }
}

